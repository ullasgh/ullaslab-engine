// Render one video + layout audit. Usage: node render.mjs --props p.json --public dir --out video.mp4 --audit layout.json
// Runs fully offline except the one-time headless Chrome download done by Remotion.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { bundle } from "@remotion/bundler";
import { renderMedia, renderStill, selectComposition } from "@remotion/renderer";

const here = path.dirname(fileURLToPath(import.meta.url));
const arg = (k) => { const i = process.argv.indexOf("--" + k); return i > 0 ? process.argv[i + 1] : undefined; };
const propsPath = arg("props"), pub = path.resolve(arg("public")), out = path.resolve(arg("out") ?? "unused.mp4"), auditOut = arg("audit");
const props = JSON.parse(fs.readFileSync(propsPath, "utf8"));
const concurrency = Number(process.env.ULLASLAB_RENDER_CONCURRENCY || 0) || undefined;

// fonts are generated by scripts/sync-fonts.mjs into remotion/public/fonts
fs.cpSync(path.join(here, "public", "fonts"), path.join(pub, "fonts"), { recursive: true, dereference: true });

const serveUrl = await bundle({ entryPoint: path.join(here, "src", "index.ts"), publicDir: pub });
const quiet = { logLevel: "error" };
const comp = await selectComposition({ serveUrl, id: "Main", inputProps: props, ...quiet });

// 1) layout audit: stills at 70% and near the end of every scene, plus first frame of the video
if (auditOut) {
  const fps = comp.fps;
  const frames = new Set([0]);
  for (const s of props.timeline.scenes) {
    const a = Math.round(s.start * fps), b = Math.round(s.end * fps);
    frames.add(Math.min(comp.durationInFrames - 1, a + Math.round((b - a) * 0.7)));
    frames.add(Math.min(comp.durationInFrames - 1, b - 6));
  }
  const auditProps = { ...props, audit: true };
  const auditComp = await selectComposition({ serveUrl, id: "Main", inputProps: auditProps, ...quiet });
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "ull-audit-"));
  const results = [];
  for (const frame of [...frames].sort((x, y) => x - y)) {
    await renderStill({ serveUrl, composition: auditComp, frame, output: path.join(tmp, "s.png"), inputProps: auditProps, ...quiet,
      onBrowserLog: (l) => {
        if (l.text.startsWith("[[AUDIT]]")) {
          const r = JSON.parse(l.text.slice(9));
          const sc = props.timeline.scenes.find((s) => frame >= Math.round(s.start * fps) && frame < Math.round(s.end * fps));
          results.push({ ...r, frame, scene: sc?.id ?? "" });
        }
      } });
  }
  fs.rmSync(tmp, { recursive: true, force: true }); // stills may contain content: never kept
  fs.writeFileSync(auditOut, JSON.stringify({ width: comp.width, height: comp.height, frames: results }));
}

if (process.argv.includes("--no-video")) { console.log("audited"); process.exit(0); }

// 2) the video (audio muxed from the audio.wav in the public dir via <Audio>)
await renderMedia({ serveUrl, composition: comp, codec: "h264", audioCodec: "aac", outputLocation: out, inputProps: props,
  crf: 20, pixelFormat: "yuv420p", concurrency, ...quiet });
console.log("rendered");
